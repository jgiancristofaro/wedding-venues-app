// Generates supabase/seed.sql from the bundled sample library so the cloud DB and the
// offline demo stay in sync. Run: npm run seed:sql
import { writeFileSync } from 'node:fs';
import { buildSeedVenues } from '../src/data/seedVenues.ts';

const q = (s: string | null | undefined) => (s == null ? 'null' : `'${s.replace(/'/g, "''")}'`);
const rows = buildSeedVenues().map(
  (v) =>
    `(${q(v.id)}, ${q(v.slug)}, ${q(JSON.stringify(v.fields))}::jsonb, ${q(JSON.stringify(v.pricing))}::jsonb, ${q(v.provenance.source)}, null, ${q(v.provenance.license)}, ${q(v.provenance.pricingAsOf)}, true, true)`,
);
const sql = `-- Generated by scripts/gen-seed-sql.ts — fictional sample venues (clearly labeled "Sample data").
insert into public.global_venues (id, slug, data, pricing, source, source_url, license_note, pricing_as_of, is_sample, published)
values
${rows.join(',\n')}
on conflict (id) do update set data = excluded.data, pricing = excluded.pricing, source = excluded.source,
  license_note = excluded.license_note, pricing_as_of = excluded.pricing_as_of, is_sample = true;
`;
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`Wrote ${rows.length} sample venues to supabase/seed.sql`);
